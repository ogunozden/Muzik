import {existsSync, readFileSync, writeFileSync} from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const DEFAULT_ROOT = process.cwd();
const DEFAULT_CATALOG = "src/data/symbtr/catalog.generated.json";
const DEFAULT_DECISIONS = "src/data/references/external-curation-decisions.json";

export function parseCliOptions(args) {
  const options = new Map();

  for (let index = 0; index < args.length; index += 1) {
    const arg = args[index];
    if (!arg.startsWith("--")) continue;

    const [key, inlineValue] = arg.slice(2).split("=", 2);
    const value = inlineValue ?? (args[index + 1]?.startsWith("--") ? "true" : args[index + 1] ?? "true");
    if (inlineValue === undefined && args[index + 1] && !args[index + 1].startsWith("--")) {
      index += 1;
    }

    const values = options.get(key) ?? [];
    values.push(value);
    options.set(key, values);
  }

  return options;
}

export function getOption(options, key, fallback = undefined) {
  const values = options.get(key);
  return values?.at(-1) ?? fallback;
}

export function findEmptyEntries(entries) {
  return entries.filter(
    (e) => (e.title === "" || e.title === "1") && e.composer === "",
  );
}

export function buildDeferDecisions(emptyEntries, existingDecisions, sourcePath) {
  const existingIds = new Set(existingDecisions.map((d) => d.catalogId));
  const decidedAt = new Date().toISOString();

  return emptyEntries
    .filter((e) => !existingIds.has(e.id))
    .map((e) => ({
      catalogId: e.id,
      status: "deferred",
      reason: "empty-title-and-composer-cannot-auto-discover",
      autoGenerated: true,
      source: sourcePath,
      decidedAt,
      notes:
        "Both title and composer are empty or placeholder (1). Auto-discovery not possible.",
    }));
}

export function deferEmptyCatalogEntries({
  root = DEFAULT_ROOT,
  catalogPath = DEFAULT_CATALOG,
  decisionsPath = DEFAULT_DECISIONS,
  write = false,
} = {}) {
  const fullCatalogPath = path.resolve(root, catalogPath);
  const fullDecisionsPath = path.resolve(root, decisionsPath);

  if (!existsSync(fullCatalogPath)) {
    return {error: `Catalog not found: ${fullCatalogPath}`, catalogPath: fullCatalogPath, decisionsPath: fullDecisionsPath};
  }

  const catalog = JSON.parse(readFileSync(fullCatalogPath, "utf8"));
  const emptyEntries = findEmptyEntries(catalog.entries);

  if (!existsSync(fullDecisionsPath)) {
    return {error: `Decisions file not found: ${fullDecisionsPath}`, catalogPath: fullCatalogPath, decisionsPath: fullDecisionsPath};
  }

  const existing = JSON.parse(readFileSync(fullDecisionsPath, "utf8"));
  const scriptSourcePath = path.relative(root, fileURLToPath(import.meta.url)).replace(/\\/g, "/");
  const newDecisions = buildDeferDecisions(
    emptyEntries,
    existing.decisions,
    scriptSourcePath,
  );

  const merged = [...existing.decisions, ...newDecisions];

  if (write) {
    writeFileSync(
      fullDecisionsPath,
      `${JSON.stringify({version: existing.version, decisions: merged}, null, 2)}\n`,
    );
  }

  return {
    emptyEntryCount: emptyEntries.length,
    existingDecisionCount: existing.decisions.length,
    newDecisionCount: newDecisions.length,
    totalDecisionCount: merged.length,
    wrote: write,
    decisionsPath: fullDecisionsPath,
  };
}

if (fileURLToPath(import.meta.url) === path.resolve(process.argv[1] ?? "")) {
  const args = process.argv.slice(2);
  const options = parseCliOptions(args);
  const write = options.has("write");

  const result = deferEmptyCatalogEntries({write});

  if (result.error) {
    console.error(result.error);
    process.exit(1);
  }

  console.log(`Catalog empty entries found: ${result.emptyEntryCount}`);
  console.log(`Existing decisions: ${result.existingDecisionCount}`);
  console.log(`New decisions to add: ${result.newDecisionCount}`);
  console.log(`Total decisions after merge: ${result.totalDecisionCount}`);

  if (write) {
    console.log(`Wrote to ${result.decisionsPath}`);
  } else {
    console.log("Dry-run mode. Use --write to persist changes.");
  }
}
